	// -----------------------------------------------------------------------
	// Internal helpers
	// -----------------------------------------------------------------------

	/**
	 * Normalises a `$where` argument from the SQL-centric interface into a
	 * MongoDB filter array.
	 *
	 * - Arrays are used as-is, optionally merged with `$parameters`.
	 * - Non-array strings (including the SQL sentinel `'1=1'`) resolve to `[]`.
	 *
	 * @param mixed $where the filter argument.
	 * @param array $parameters additional conditions to merge.
	 * @return array the MongoDB filter document.
	 */
	protected function normalizeFilter(mixed $where, array $parameters = []): array
	{
		$filter = is_array($where) ? $where : [];
		if ($parameters !== []) {
			$filter = array_merge($filter, $parameters);
		}
		return $filter;
	}

	/**
	 * Converts a PRADO ordering array (`[field => 'asc'|'desc']`) to a
	 * MongoDB sort document (`[field => 1|-1]`).
	 *
	 * @param array $ordering PRADO-style ordering.
	 * @return array MongoDB sort document.
	 */
	protected function normalizeOrdering(array $ordering): array
	{
		$sort = [];
		foreach ($ordering as $field => $direction) {
			$sort[$field] = (strtolower((string) $direction) === 'asc') ? 1 : -1;
		}
		return $sort;
	}
