	 *
	 * @param IDataCommand $command ignored.
	 * @param array $values ignored.
	 */
	public function bindArrayValues($command, $values): void
	{
		// No-op: MongoDB commands do not use bound parameters.
	}

	// -----------------------------------------------------------------------
	// MongoDB-specific helpers (public, not part of IDataCommandBuilder)
	// -----------------------------------------------------------------------

	/**
	 * Applies limit and skip values to a query options array in-place.
	 * @param array $options query options to modify.
	 * @param int $limit maximum documents to return; 0 or negative means no limit.
	 * @param int $skip documents to skip; 0 or negative means no skip.
	 */
	public function applyLimitSkip(array &$options, int $limit, int $skip): void
	{
		if ($limit > 0) {
			$options['limit'] = $limit;
		}
		if ($skip > 0) {
			$options['skip'] = $skip;
		}
	}

	/**
	 * Applies a sort document to a query options array in-place.
	 * @param array $options query options to modify.
	 * @param array $sort sort document, e.g. `['name' => 1, 'createdAt' => -1]`.
	 */
	public function applySort(array &$options, array $sort): void
	{
		if ($sort !== []) {
			$options['sort'] = $sort;
		}
	}

	/**
	 * Applies a field projection to a query options array in-place.
	 *
	 * @param array $options query options to modify.
	 * @param mixed $fields
	 *   - `null`  → project all known schema fields as an inclusion projection.
	 *   - `'*'`   → no projection (all fields, MongoDB default).
	 *   - `array` → used verbatim as the projection document.
	 *   - `string` (comma-separated) → converted to an inclusion projection.
	 */
	public function applyProjection(array &$options, mixed $fields): void
	{
		if ($fields === '*' || $fields === []) {
			return;
		}
		if ($fields === null) {
			$knownFields = $this->_collectionInfo->getFieldNames();
			if ($knownFields !== []) {
				$options['projection'] = array_fill_keys($knownFields, 1);
			}
			return;
		}
		if (is_array($fields)) {
			$options['projection'] = $fields;
			return;
		}
		if (is_string($fields)) {
			$list = array_values(array_filter(array_map('trim', explode(',', $fields))));
			if ($list !== []) {
				$options['projection'] = array_fill_keys($list, 1);
			}
		}
	}

	/**
	 * Builds a MongoDB `$or` filter that performs a case-insensitive regex search
	 * across the given fields for each keyword.
	 *
	 * Equivalent to {@see TDbCommandBuilder::getSearchExpression} for MongoDB.
	 *
	 * @param array $fields field names to search.
	 * @param string $keywords space-separated search terms.
	 * @return array a MongoDB filter document, or `[]` if no terms or fields.
	 */
	public function getSearchFilter(array $fields, string $keywords): array
	{
		$words = array_filter(preg_split('/\s+/', trim($keywords)));
		if ($words === [] || $fields === []) {
			return [];
		}
		$conditions = [];
		foreach ($fields as $field) {
			foreach ($words as $word) {
				$conditions[] = [
					$field => [
						'$regex' => preg_quote((string) $word, '/'),
						'$options' => 'i',
					],
				];
			}
		}
		return ['$or' => $conditions];
	}

	/**
