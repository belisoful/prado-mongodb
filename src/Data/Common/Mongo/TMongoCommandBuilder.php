	/**
	 * Creates a bare command for the collection.
	 *
	 * The `$sql` argument is ignored (MongoDB has no SQL). The returned command
	 * targets this builder's collection with an empty filter and default OP_FIND
	 * operation; callers configure it further via the fluent builder API.
	 *
	 * @param mixed $sql ignored.
	 * @return IDataCommand
	 */
	public function createCommand($sql): IDataCommand
	{
		return $this->_connection->createCommand($this->_collectionInfo->getCollectionName());
	}

	/**
	 * No-op for MongoDB.
	 *
	 * SQL drivers bind typed column values into a prepared statement.
	 * MongoDB does not use bound parameters.
	 *
	 * @param IDataCommand $command ignored.
	 * @param array $values ignored.
	 */
	public function bindColumnValues($command, $values): void
	{
		// No-op: MongoDB commands do not use bound parameters.
	}

	/**
	 * No-op for MongoDB.
	 *
	 * SQL drivers bind positional or named parameter arrays into a prepared
